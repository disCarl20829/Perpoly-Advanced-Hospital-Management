// ============================================================
// REPORTS (pulls from other subsystems)
// ============================================================

/**
 * Generate an aggregated report across cashier, laboratory, and inventory.
 * @param {object} filters - { from, to }
 * @returns {object} report data
 */
export async function generateReport(filters = {}) {
    const [cashier, laboratory, inventory, expenses] = await Promise.all([
        accountingRepo.getCashierTransactions(filters),
        accountingRepo.getLaboratoryResults(filters),
        accountingRepo.getInventoryMovements(filters),
        accountingRepo.findAllExpenses(filters)
    ]);

    return {
        period: {
            from: filters.from || null,
            to: filters.to || null
        },
        cashier: {
            count: cashier.length,
            transactions: cashier
        },
        laboratory: {
            count: laboratory.length,
            results: laboratory
        },
        inventory: {
            count: inventory.length,
            movements: inventory
        },
        expenses: {
            count: expenses.length,
            items: expenses
        }
    };
}

/**
 * Log a master export (Excel file generated by FastAPI later).
 * @param {string} requestedBy - UUID
 * @param {object} filters - { from, to }
 * @param {string} filePath - path to the generated file
 * @returns {object} created export log
 */
export async function logMasterExport(requestedBy, filters = {}, filePath = null) {
    return await accountingRepo.createExportLog({
        export_type: 'master',
        system: null,
        requested_by: requestedBy,
        filters,
        file_path: filePath
    });
}

/**
 * Log a per-system export.
 * @param {string} system - 'cashier' | 'laboratory' | 'inventory'
 * @param {string} requestedBy - UUID
 * @param {object} filters - { from, to }
 * @param {string} filePath - path to the generated file
 * @returns {object} created export log
 */
export async function logSystemExport(system, requestedBy, filters = {}, filePath = null) {
    return await accountingRepo.createExportLog({
        export_type: 'per_system',
        system,
        requested_by: requestedBy,
        filters,
        file_path: filePath
    });
}
