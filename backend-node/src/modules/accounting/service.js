import * as accountingRepo from './repository.js';

// ============================================================
// EXPENSES
// ============================================================

/**
 * Record an expense.
 * @param {object} data - { source_system, source_reference_id, description, amount, incurred_at }
 * @returns {object} created expense
 */
export async function recordExpense(data) {
    return await accountingRepo.createExpense(data);
}

/**
 * Get expenses with optional filters.
 * @param {object} filters - { source_system, from, to }
 * @returns {array} list of expenses
 */
export async function getExpenses(filters = {}) {
    return await accountingRepo.findAllExpenses(filters);
}

/**
 * Get a single expense by ID.
 * @param {string} id - UUID
 * @returns {object} expense
 */
export async function getExpenseById(id) {
    const expense = await accountingRepo.findExpenseById(id);
    if (!expense) {
        const err = new Error('Expense not found');
        err.status = 404;
        throw err;
    }
    return expense;
}

/**
 * Get expense summary grouped by source system.
 * @param {object} filters - { from, to }
 * @returns {array} grouped totals
 */
export async function getExpenseSummary(filters = {}) {
    return await accountingRepo.getExpenseSummary(filters);
}

